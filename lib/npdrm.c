void init_npdrm(uint8_t* cart_secret, uint8_t* console_id, SceNpDrmActivationData* activation_data) { 
	LOG_LINE("[NpDrm] Initalizing NpDrm_emu");

	if (cart_secret != NULL) { set_cart_secret(cart_secret); }
	if (console_id != NULL) { set_console_id(console_id); }
	if (activation_data != NULL) { set_activation_data(activation_data); }
	if (activation_data != NULL && console_id != NULL) { decrypt_key_table(); }

	LOG_BOOL("[NpDrm] Has Cartridge", G_CART_INSERTED);
	LOG_BOOL("[NpDrm] Activated", G_ACTIVATED);

}


// the following would run in secure processor:
void decrypt_bind_data(char* key, size_t keyLen, char* bindData, size_t bindDataLen) { // ksceSblAuthMgrDecBindData
	uint8_t bind_hmac[0x20] = { 0 };
	uint8_t aes_key[0x10] = { 0 };
	uint8_t aes_iv[0x10] = { 0 };

    // derive aes key from bind data, and BIND_HMAC
	hmac_sha256(BIND_HMAC_KEY, sizeof(BIND_HMAC_KEY), bindData, bindDataLen, bind_hmac, sizeof(bind_hmac));

    // first 0x10 bytes of resulting hmac_sha256 of binddata; is aes key,
    // the last 0x10 bytes, are the iv
	memcpy(aes_key, bind_hmac + 0x00, sizeof(aes_key));
	memcpy(aes_iv, bind_hmac + 0x10, sizeof(aes_iv));

    LOG_BUFFER("[SblAuthMgr_sm] BindData Derived Key", aes_key, sizeof(aes_key));
    LOG_BUFFER("[SblAuthMgr_sm] BindData Derived IV", aes_iv, sizeof(aes_iv));

    // finally aes-cbc-decrypt.
	aes_cbc_dec(key, keyLen, aes_key, aes_iv);
}


int decrypt_klicensee(uint8_t* klicensee, SceNpDrmLicense* license, uint8_t vita) { // ksceNpDrmGetRifVitaKey
	SceNpBindData bind_data = { 0 };

	uint8_t is_digital = ((license->license_flags & 0x4) == 0);
	uint8_t is_psp = !vita && is_digital;
	uint8_t is_drmbind = (license->license_flags >> 8) != 0b00001101;
	uint8_t is_debug = (license->license_flags >> 8) == 0;

	/*
		original asm: 

		ldrh r2, [r0, #0x6]
		rev16 r3, r2
		lsls r1,r3,#0x17
		it mi
		movmi r5, #0x1
		ands r1,r3,#0x400 
	
		re-implementation: 

		uint32_t r1, r2, r3, r4, r5, n;

		r2 = license->license_flags; // ldrh r2,[r0,#0x6]
		r3 = swap16(r2); //rev16 r3, r2

		r1 = r3 << 0x17; // lsls r1,r3,#0x17
		n = r1 >> 31;

		if(n == 1) { // it mi
			r5 = 0x5; // movmi r5, #0x1
		}
		r1 = r3 & 0x400; // ands r1, r3
	*/


	LOG_LINE("[RIF] Version: 0x%x", license->version);
	LOG_LINE("[RIF] Version Flag: 0x%x", license->version_flags);
	LOG_LINE("[RIF] SKU Flag: 0x%x", license->sku_flag);
	LOG_LINE("[RIF] License Flags: 0x%x", license->license_flags);

	LOG_LINE("[RIF] Content Id: %s", license->content_id);
	LOG_LINE("[RIF] Account Id: 0x%"PRIx64"", license->account_id);
	LOG_LINE("[RIF] Start Time: 0x%"PRId64"", license->start_time);
	LOG_LINE("[RIF] Expiration Time: 0x%"PRId64"", license->expiration_time);
	LOG_BOOL("[RIF] Upgradable App", license->debug_upgradable);
	LOG_BUFFER("[RIF] OpenPSID", license->open_psid, sizeof(license->open_psid));
	LOG_BUFFER("[RIF] CMD56 Rif Hash", license->cmd56_handshake_part, sizeof(license->cmd56_handshake_part));

	LOG_BOOL("[RIF] Is Digital", is_digital);
	LOG_LINE("[RIF] Platform: %s", is_psp ? "PSP" : "Vita");
	LOG_LINE("[RIF] Drm Type: %s", is_drmbind ? "Bind" : "Free");
	LOG_BOOL("[RIF] Is Debug", is_debug);


	uint8_t check_ecdsa = 0;
	uint8_t rsa_keyindex = 0;

	// handle signature check ..
	if (swap16(license->license_flags) & 0x400 == 0 && license->license_flags != 0) {
		if ((license->license_flags & 1) != 0) {
			/* check ecdsa ..*/
			check_ecdsa = 1;
		}
		/* check rif keyindex 1 */
		LOG_BUFFER("[RIF] RSA Public Key", RIF_KEY_3, sizeof(RIF_KEY_1));
		rsa_keyindex = 1;
	}
	else if(license->license_flags == 0) {
		/* check rif keyindex 2 */
		LOG_BUFFER("[RIF] RSA Public Key", RIF_KEY_3, sizeof(RIF_KEY_2));
		rsa_keyindex = 2;
	}
	else {
		/* check rif keyindex 3 */
		LOG_BUFFER("[RIF] RSA Public Key", RIF_KEY_3, sizeof(RIF_KEY_3));
		rsa_keyindex = 3;
	}

	LOG_BOOL("[RIF] Check ECDSA", check_ecdsa);
	LOG_LINE("[RIF] RSA KeyIndex: 0x%x", rsa_keyindex);
	

	// copy key2 to klicensee buffer ...
	memcpy(klicensee, license->key2, sizeof(license->key2));

	// copy license to binddata license buffer ..
	memcpy(bind_data.license, license, sizeof(bind_data.license));

	// if not vita, do it the psp way;
	if (!vita && is_psp) {
		if (!G_ACTIVATED) return 0;

		int key_id = decrypt_keyid(license->key_table);
		LOG_LINE("[RIF] [PSP] Key ID: 0x%X", key_id);

		aes_ecb_out_dec(klicensee, license->key1, G_ACTIVATION_DATA.primary_key_table[key_id]);
		
		if (is_debug) {
			memset(klicensee, 0xAA, KLICENSEE_SIZE);
		}
		
		LOG_BUFFER("[RIF] [PSP] Version Key", klicensee, KLICENSEE_SIZE);
		return 1;
	}

	if (is_digital) { // handle digital games ..
		if (is_drmbind) { // read activation if npdrm bind;
			if (!G_ACTIVATED) return 0;
			memcpy(bind_data.key, G_ACTIVATION_DATA.primary_key_table, sizeof(bind_data.key));
		}
		else { // if npdrm free, use the rif key directly;
			memcpy(bind_data.key, VITA_RIF_KEY, sizeof(bind_data.key));
		}
	}
	else { // handle physical games ..
		if (!vita) { // if calling the PSP function on a Phyiscal game license; then we directly use key1.
			memcpy(klicensee, license->key1, KLICENSEE_SIZE);
		}
		else { // otherwise, the bind key is the cart secret.
			if (!G_CART_INSERTED) return 0;
			memcpy(bind_data.key, G_CART_SECRET, sizeof(bind_data.key));
		}
	}
	
    
	LOG_BUFFER("[RIF] Bind Key", bind_data.key, sizeof(bind_data.key));

    // decrypt key2 to klicensee using the bind data specified,
	decrypt_bind_data(klicensee, KLICENSEE_SIZE, (char*)&bind_data, sizeof(SceNpBindData));

    // if the debug flag is set, then the klicensee is all 0x00.
	if (is_debug) {
		memset(klicensee, 0x00, KLICENSEE_SIZE);
	}

	LOG_BUFFER("[RIF] KLicensee", klicensee, KLICENSEE_SIZE);

	return 1;
}

// NoNpDrm;

int make_nonpdrm_license(SceNpDrmLicense* license, uint8_t* klicensee) {

	SceNpDrmLicense new_license = { 0 };

	new_license.account_id = 0x0123456789ABCDEFLL;
	new_license.version = swap16(1);
	new_license.version_flags = swap16(1);
	new_license.license_type = swap16(1);

	new_license.license_flags = swap16(swap16(license->license_flags) & ~0x400);
	new_license.flags = license->flags;

	if (swap32(license->sku_flag) == 1 || swap32(license->sku_flag) == 3) {
		new_license.sku_flag = swap32(3);
	}
	else {
		new_license.sku_flag = swap32(0);
	}

	memcpy(new_license.content_id, license->content_id, sizeof(license->content_id));
	memcpy(new_license.key1, klicensee, sizeof(new_license.key1));

	memcpy(license, &new_license, sizeof(SceNpDrmLicense));

	return 1;
}