static SceNpDrmActivationData G_ACTIVATION_DATA = { 0 };
static uint8_t G_CART_SECRET[0x20] = { 0 };
static uint8_t G_CONSOLE_ID[0x10] = { 0 };
static uint8_t G_ACTIVATED = 0;
static uint8_t G_CART_INSERTED = 0;


int decrypt_keyid(uint8_t* key_id_block) {
	aes_ecb_dec(key_id_block, PSP_RIF_KEY);

	int key_id = 0;
	memcpy(&key_id, key_id_block + 0xC, sizeof(key_id));

	return key_id;
}

void decrypt_key_table() {

	// generate per console act key.
	uint8_t act_key_perconsole[0x10] = { 0 };
	aes_ecb_out_enc(act_key_perconsole, ACT_KEY, G_CONSOLE_ID);
	LOG_BUFFER("[ACT] Per-Console Activation Key", act_key_perconsole, sizeof(act_key_perconsole));

	// decrypt all activation keys
	for (int i = 0; i < sizeof(G_ACTIVATION_DATA.primary_key_table) / 0x10; i++) {
		aes_ecb_dec(G_ACTIVATION_DATA.primary_key_table[i], act_key_perconsole);
		LOG_BUFFER("[ACT] Primary Key Table", G_ACTIVATION_DATA.primary_key_table[i], sizeof(G_ACTIVATION_DATA.primary_key_table[i]));
	}

	G_ACTIVATED = 1;

	// print act.dat

	LOG_LINE("[ACT] Version: 0x%x", G_ACTIVATION_DATA.version);
	LOG_LINE("[ACT] Version Flag: 0x%x", G_ACTIVATION_DATA.version_flag);
	LOG_LINE("[ACT] Activation Type: 0x%x", G_ACTIVATION_DATA.act_type);

	LOG_LINE("[ACT] Account Id: 0x%" PRId64 "x", G_ACTIVATION_DATA.account_id);
	LOG_BUFFER("[ACT] OpenPSID", G_ACTIVATION_DATA.openpsid, sizeof(G_ACTIVATION_DATA.openpsid));

}

